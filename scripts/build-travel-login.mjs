import fs from 'node:fs';
import sharp from 'sharp';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import * as lucide from 'lucide-react';
const root=new URL('../',import.meta.url);
const at=p=>new URL(p,root);
const names=['Mountain','Globe','ChevronDown','CalendarDays','Navigation','UsersRound','ArrowRight','Heart','Mail','LockKeyhole','Eye','EyeOff','Check','X'];
const icons=Object.fromEntries(names.map(name=>[name,renderToStaticMarkup(React.createElement(lucide[name],{size:20,strokeWidth:1.6,'aria-hidden':'true'}))]));
const input=Buffer.from(fs.readFileSync(at('travel-hero.b64'),'utf8').trim(),'base64');
fs.mkdirSync(at('travel-assets'),{recursive:true});
const hero=await sharp(input).resize({width:1800,withoutEnlargement:true}).jpeg({quality:86,mozjpeg:true}).toBuffer();
const thumb=await sharp(input).resize(600,430,{fit:'cover',position:'southeast'}).jpeg({quality:86,mozjpeg:true}).toBuffer();
const munnar=await sharp(fs.readFileSync(at('public/images/munnar.webp'))).resize(430,580,{fit:'cover'}).jpeg({quality:85,mozjpeg:true}).toBuffer();
fs.writeFileSync(at('travel-assets/santorini-hero.jpg'),hero);fs.writeFileSync(at('travel-assets/santorini-card.jpg'),thumb);fs.writeFileSync(at('travel-assets/munnar-card.jpg'),munnar);
const uri=b=>'data:image/jpeg;base64,'+b.toString('base64');
let html=fs.readFileSync(at('travel-login.template.html'),'utf8');
html=html.replace(/<img class="stamp"[^>]*>/,'');
for(const provider of ['Google','Apple','Microsoft'])html=html.replace('<img src="__'+provider.toUpperCase()+'__" alt="'+provider+'">','<span style="font-size:12px;font-weight:500">'+provider+'</span>');
html=html.replaceAll('__HERO__',uri(hero)).replaceAll('__SANTORINI__',uri(thumb)).replaceAll('__MUNNAR__',uri(munnar)).replace('__ICONS_JSON__',JSON.stringify(icons));
html=html.replace(/__ICON_(\w+)__/g,(_,name)=>icons[name]||'');
if(/__[A-Z_]+__/.test(html))throw Error('Unresolved placeholders');
if(!fs.existsSync(at('login-minimal.html')))fs.copyFileSync(at('login-offline.html'),at('login-minimal.html'));
fs.writeFileSync(at('travel-login.html'),html);fs.writeFileSync(at('login-offline.html'),html);
console.log('Offline travel login built:',Math.round(Buffer.byteLength(html)/1024),'KB. All photos and icons embedded.');
