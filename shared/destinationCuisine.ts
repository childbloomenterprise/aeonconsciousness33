export const foodRegions = ["Kerala", ...Object.keys(destinationMenus)];
export function cuisineRegion(destination = "") {
  const text = destination.toLowerCase();
  if (
    /kerala|kochi|cochin|munnar|alleppey|alappuzha|wayanad|kumarakom|varkala|thekkady|athirappilly/.test(
      text,
    )
  )
    return "Kerala";
  if (/bombay/.test(text)) return "Mumbai";
  if (/uae|emirat|abu dhabi/.test(text)) return "Dubai";
  if (/panaji|panjim|calangute/.test(text)) return "Goa";
  if (/madras/.test(text)) return "Chennai";
  if (/calcutta/.test(text)) return "Kolkata";
  return (
    Object.keys(destinationMenus).find((city) =>
      text.includes(city.toLowerCase()),
    ) || null
  );
}
export function mealsForDestination(
  destination = "",
): readonly DestinationMeal[] {
  const region = cuisineRegion(destination);
  return region === "Kerala"
    ? mealSuggestions
    : region
      ? destinationMenus[region]
      : [];
}
